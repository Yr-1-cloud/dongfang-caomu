def build_item(id_, name, pinyin, tag, summary, fields, type_):
    return {
        "id": id_, "type": type_, "name": name, "pinyin": pinyin,
        "tag": tag, "summary": summary,
        "fields": [{"label": l, "value": v} for l, v in fields],
    }


def main() -> None:
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    plan = [
        ("herbs", HERBS, "herb"), ("formulas", FORMULAS, "formula"),
        ("diet", DIET, "diet"), ("meridian", MERIDIAN, "meridian"),
        ("constitution", CONSTITUTION, "constitution"), ("classic", CLASSIC, "classic"),
        ("doctors", DOCTORS, "doctor"), ("stories", STORIES, "story"),
    ]
    added = 0
    for key, rows, type_ in plan:
        have = {x.get("id") for x in data[key]}
        for id_, name, pinyin, tag, summary, fields in rows:
            if id_ in have:
                continue
            data[key].append(build_item(id_, name, pinyin, tag, summary, fields, type_))
            added += 1

    # 发展历程：按“插入到指定纪元之前”的规则插入，保持时间顺序
    for era, title, desc, before_era in HISTORY_NEW:
        if any(h.get("era") == era for h in data["history"]):
            continue
        idx = next((i for i, h in enumerate(data["history"]) if h.get("era") == before_era), len(data["history"]))
        data["history"].insert(idx, {"era": era, "title": title, "desc": desc})
        added += 1

    CATALOG.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"新增 {added} 条")
    for k, v in data.items():
        if isinstance(v, list):
            print(f"  {k:14s} {len(v)} 条")


if __name__ == "__main__":
    main()
